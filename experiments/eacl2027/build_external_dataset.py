def _spec_examples(rule_id: str) -> set[str]:
    path = ROOT / "rules" / rule_id / "rule.py"
    loaded = load_rule_file(path, "experiment")
    if len(loaded) != 1:
        raise RuntimeError(f"expected one rule in {path}")
    return {
        str(value) for value, _expected in rules_api.spec_examples(loaded[0].spec or "")
    }


def _load_source_snapshot(path: Path = SOURCE_SNAPSHOT) -> dict[str, Any]:
    try:
        snapshot = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"invalid external source snapshot {path}: {exc}") from exc
    if not isinstance(snapshot, dict):
        raise ValueError("external source snapshot must be a JSON object")
    source_corpus = snapshot.get("source_corpus")
    records = snapshot.get("records")
    if not isinstance(source_corpus, dict) or not isinstance(records, list):
        raise ValueError("external source snapshot requires source_corpus and records")
    if source_corpus != PINNED_SOURCE_CORPUS:
        raise ValueError("external source snapshot changed the pinned corpus identity")
    if len(records) != 8:
        raise ValueError(
            f"external source snapshot has {len(records)} records, expected 8"
        )

    rule_ids = set()
    record_ids = set()
    for record in records:
        if not isinstance(record, dict):
            raise ValueError("external source snapshot records must be objects")
        rule_id = record.get("rule_id")
        record_id = record.get("record_id")
        raw = record.get("raw_record")
        normalized = record.get("normalized_source")
        adaptation = record.get("adaptation")
        if not isinstance(rule_id, str) or not isinstance(record_id, int):
            raise ValueError(
                "source records require string rule_id and integer record_id"
            )
        if rule_id in rule_ids or record_id in record_ids:
            raise ValueError("duplicate rule_id or record_id in source snapshot")
        rule_ids.add(rule_id)
        record_ids.add(record_id)
        if not isinstance(raw, dict) or set(raw) != CSV_FIELDS:
            raise ValueError(f"{rule_id}: raw_record does not match the CSV schema")
        if raw["id"] != str(record_id):
            raise ValueError(f"{rule_id}: raw record id does not match record_id")
        if not isinstance(record.get("physical_line_end"), int):
            raise ValueError(f"{rule_id}: physical_line_end must be an integer")
        if not isinstance(normalized, dict) or {
            "repository",
            "repository_license",
            "file_path",
            "instruction_line",
        } != set(normalized):
            raise ValueError(f"{rule_id}: invalid normalized_source")
        if normalized["instruction_line"] != int(raw["line"]):
            raise ValueError(f"{rule_id}: normalized instruction line changed")
        if not isinstance(adaptation, dict) or {
            "trigger",
            "input_field",
            "coverage",
            "covered_clause",
        } - set(adaptation):
            raise ValueError(f"{rule_id}: invalid adaptation metadata")
        if (
            adaptation["trigger"] != "PreToolUse"
            or adaptation["input_field"] != "/tool_input"
        ):
            raise ValueError(f"{rule_id}: unsupported trigger/input adaptation")
        if adaptation["coverage"] not in {"full_instruction", "extracted_sub_rule"}:
            raise ValueError(f"{rule_id}: invalid adaptation coverage")
        if adaptation["coverage"] == "extracted_sub_rule" and not adaptation.get(
            "excluded_clause"
        ):
            raise ValueError(f"{rule_id}: extracted sub-rule lacks excluded_clause")
    if rule_ids != set(RULES):
        raise ValueError("source snapshot and rule cases differ")
    return snapshot


def verify_source_csv(
    csv_path: Path, snapshot_path: Path = SOURCE_SNAPSHOT
) -> dict[str, Any]:
    """Verify the pinned corpus file and all selected records byte-for-byte."""

    snapshot = _load_source_snapshot(snapshot_path)
    expected_sha = str(snapshot["source_corpus"].get("file_sha256", ""))
    actual_sha = hashlib.sha256(csv_path.read_bytes()).hexdigest()
    if actual_sha != expected_sha:
        raise ValueError(
            f"source corpus SHA-256 mismatch: expected {expected_sha}, got {actual_sha}"
        )

    wanted = {int(record["record_id"]): record for record in snapshot["records"]}
    observed: dict[int, tuple[dict[str, str], int]] = {}
    with csv_path.open(encoding="utf-8", newline="") as stream:
        reader = csv.DictReader(stream)
        if set(reader.fieldnames or []) != CSV_FIELDS:
            raise ValueError(
                "source corpus CSV header does not match the pinned schema"
            )
        for row in reader:
            try:
                record_id = int(row["id"])
            except (KeyError, TypeError, ValueError) as exc:
                raise ValueError(
                    f"invalid source corpus record at line {reader.line_num}"
                ) from exc
            if record_id in wanted:
                if record_id in observed:
                    raise ValueError(f"duplicate source corpus record id {record_id}")
                observed[record_id] = (dict(row), reader.line_num)

    missing = sorted(set(wanted) - set(observed))
    if missing:
        raise ValueError(f"source corpus is missing selected records {missing}")
    for record_id, expected in wanted.items():
        actual_record, physical_line_end = observed[record_id]
        if actual_record != expected["raw_record"]:
            differing = sorted(
                key
                for key in CSV_FIELDS
                if actual_record.get(key) != expected["raw_record"].get(key)
            )
            raise ValueError(
                f"source corpus record {record_id} differs in fields {differing}"
            )
        if physical_line_end != expected["physical_line_end"]:
            raise ValueError(
                f"source corpus record {record_id} ends on physical line "
                f"{physical_line_end}, expected {expected['physical_line_end']}"
            )
    return {
        "file": str(csv_path),
        "file_sha256": actual_sha,
        "records_verified": len(observed),
        "record_ids": sorted(observed),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--verify-source-csv",
        type=Path,
        help="verify the pinned Reporails validation_key.csv before building",
    )
    parser.add_argument(
        "--verify-only",
        action="store_true",
        help="verify the source CSV without regenerating benchmark files",
    )
    args = parser.parse_args(argv)
    if args.verify_only and args.verify_source_csv is None:
        parser.error("--verify-only requires --verify-source-csv")
    if args.verify_source_csv is not None:
        source_report = verify_source_csv(args.verify_source_csv)
        if args.verify_only:
            print(json.dumps(source_report, indent=2, sort_keys=True))
            return 0

    source_snapshot = _load_source_snapshot()
    sources = {str(record["rule_id"]): record for record in source_snapshot["records"]}
    protocol = json.loads((ROOT / "protocol.json").read_text(encoding="utf-8"))
    protocol_version = str(protocol["protocol_version"])
    rows = []
    rule_source_hashes = {}
    for rule_id, pairs in RULES.items():
        if len(pairs) != PAIRS_PER_RULE:
            raise ValueError(
                f"{rule_id} has {len(pairs)} pairs, expected {PAIRS_PER_RULE}"
            )
        rule_path = ROOT / "rules" / rule_id / "rule.py"
        rule_source_hash = hashlib.sha256(rule_path.read_bytes()).hexdigest()
        rule_source_hashes[rule_id] = rule_source_hash
        examples = _spec_examples(rule_id)
        for index, (positive, negative) in enumerate(pairs, 1):
            pair_id = f"external-{rule_id}-pair-{index:02d}"
            for polarity, value, expected in (
                ("positive", positive, "WARNING"),
                ("negative", negative, "OK"),
            ):
                if value in examples:
                    raise ValueError(
                        f"{rule_id} case reuses a specification example: {value!r}"
                    )
                rows.append(
                    {
                        "case_id": f"{pair_id}-{polarity}",
                        "pair_id": pair_id,
                        "rule_id": rule_id,
                        "hook": "PreToolUse",
                        "input": value,
                        "expected": expected,
                        "split": "test",
                        "provenance": "synthetic_for_external_instruction",
                        "source_hash": rule_source_hash,
                        "note": (
                            "external instruction; synthetic contrastive input; "
                            "label fixed by construction"
                        ),
                    }
                )
    random.Random(SEED).shuffle(rows)
    if len({row["case_id"] for row in rows}) != len(rows):
        raise ValueError("duplicate case ids")
    if len({(row["rule_id"], row["input"]) for row in rows}) != len(rows):
        raise ValueError("duplicate rule/input pairs")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    body = "".join(
        json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n" for row in rows
    )
    OUTPUT.write_text(body, encoding="utf-8")
    source_manifest: dict[str, Any] = {}
    source_commit = str(source_snapshot["source_corpus"]["commit"])
    source_file = str(source_snapshot["source_corpus"]["file"])
    for rule_id, record in sources.items():
        instruction = str(record["raw_record"]["text"])
        source_manifest[rule_id] = {
            **record,
            "instruction_sha256": hashlib.sha256(
                instruction.encode("utf-8")
            ).hexdigest(),
            "corpus_record_url": (
                "https://github.com/reporails/30k-corpus/blob/"
                f"{source_commit}/{source_file}#L{record['physical_line_end']}"
            ),
        }
    snapshot_relative = SOURCE_SNAPSHOT.relative_to(ROOT).as_posix()
    manifest = {
        "name": "rap-external-selected-rules-v1",
        "protocol_version": protocol_version,
        "seed": SEED,
        "selection": "purposive, eligibility-screened, behavior-diverse",
        "selection_limit": (
            "Not a prevalence sample; no claim about the fraction of public "
            "instructions expressible by RAP."
        ),
        "cases": len(rows),
        "pairs": len(rows) // 2,
        "rules": len(RULES),
        "cases_per_rule": PAIRS_PER_RULE * 2,
        "provenance": "synthetic_for_external_instruction",
        "exact_spec_example_reuse_forbidden": True,
        "source_corpus": source_snapshot["source_corpus"],
        "source_snapshot": {
            "file": snapshot_relative,
            "sha256": hashlib.sha256(SOURCE_SNAPSHOT.read_bytes()).hexdigest(),
        },
        "sources": source_manifest,
        "sha256": hashlib.sha256(body.encode("utf-8")).hexdigest(),
        "rule_source_sha256": rule_source_hashes,
    }
    MANIFEST.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(json.dumps(manifest, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
