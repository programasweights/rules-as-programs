from rules_as_programs import rule


SPEC = """The input is the exact serialized JSON value of a Codex PreToolUse
/tool_input field. Decide whether it creates or amends a Git commit whose
message credits an AI system or says the change was generated by one. Ordinary
commit messages, author-supplied human attribution, and prose that merely
discusses AI attribution without executing a commit are allowed.
Return ONLY one of: OK, WARNING

Input: {"command":"git commit -m 'Fix parser' -m 'Generated with Claude Code'"}
Output: WARNING

Input: {"command":"git commit --amend -m 'Docs update (written by AI)'"}
Output: WARNING

Input: {"command":"git commit -m 'Fix parser edge case'"}
Output: OK

Input: {"patch":"Add policy text: do not write Generated by AI in commits."}
Output: OK"""


@rule(
    id="g3b7damk0b5xgdj6",
    name="Do not credit AI in commit messages",
    trigger="PreToolUse",
    spec=SPEC,
)
def no_ai_credit(ctx):
    """Do not add AI self-credit to commit messages."""
    return ctx.result(ctx.paw(SPEC)(ctx.input))
